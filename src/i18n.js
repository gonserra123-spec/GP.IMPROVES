/* JSON-LD coherente con clinic.js (DEMO) */
export function buildJsonLd(lang) {
  const t = ui[lang];
  const a = clinic.address;
  const dayMap = { Mo: 'Monday', Tu: 'Tuesday', We: 'Wednesday', Th: 'Thursday', Fr: 'Friday', Sa: 'Saturday', Su: 'Sunday' };
  return {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': ['MedicalClinic', 'BeautySalon'],
        '@id': `${clinic.url}/#clinic`,
        name: pick(clinic.legalName, lang),
        description: t.meta.description,
        url: clinic.url,
        image: `${clinic.url}/og-image.png`,
        logo: `${clinic.url}/favicon.svg`,
        telephone: clinic.phone,
        email: clinic.email,
        inLanguage: lang,
        priceRange: '€€',
        address: {
          '@type': 'PostalAddress',
          streetAddress: a.street,
          postalCode: a.postalCode,
          addressLocality: a.city,
          addressRegion: a.region,
          addressCountry: a.country,
        },
        geo: { '@type': 'GeoCoordinates', latitude: a.geo.lat, longitude: a.geo.lng },
        openingHoursSpecification: clinic.hours
          .filter((h) => h.schema)
          .map((h) => ({
            '@type': 'OpeningHoursSpecification',
            dayOfWeek: h.schema.d.map((d) => dayMap[d]),
            opens: h.schema.o,
            closes: h.schema.c,
          })),
        availableService: treatments.map((tr) => ({ '@type': 'MedicalProcedure', name: pick(tr.name, lang), description: pick(tr.desc, lang) })),
      },
      {
        '@type': 'FAQPage',
        mainEntity: faqs.map((f) => ({
          '@type': 'Question',
          name: pick(f.q, lang),
          acceptedAnswer: { '@type': 'Answer', text: pick(f.a, lang) },
        })),
      },
    ],
  };
}
